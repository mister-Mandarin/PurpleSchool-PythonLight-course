# **Описание**: Создайте функцию для обработки пользовательского ввода с использованием блока else после try для выполнения действий при успешном преобразовании строки в число
#
# **Входные данные**: Строка передается как аргумент функции
#
# **Выходные данные**: Результат обработки или сообщение об ошибке
#
# **Ограничения**: Строка может содержать некорректные символы для преобразования в число
#
# **Примеры**:
# Входные данные: convert_and_process("42")
# Output: Число успешно обработано: 42
#
# Входные данные: convert_and_process("abc")
# Output: Ошибка: невозможно преобразовать в число

def convert_and_process(input_string):
    try:
        number = float(input_string)
        print(f"Число успешно обработано: {number}")
    except ValueError:
        print("Ошибка: невозможно преобразовать в число")

